import logging
from decimal import Decimal

from django.shortcuts import get_object_or_404
from drf_spectacular.types import OpenApiTypes
from drf_spectacular.utils import extend_schema
from rest_framework import status
from rest_framework.permissions import IsAuthenticated
from rest_framework.response import Response
from rest_framework.views import APIView

from market_place.models import EventInfo

from .models import AffiliateLink, AffiliateProfile, AffiliateSale
from .serializers import (
    AffiliateApplySerializer,
    AffiliateDashboardSerializer,
    AffiliateLinkSerializer,
    AffiliateSaleSerializer,
    AffiliateStatusSerializer,
)
from .utils import pay_out, record_attribution, sweep_payable

logger = logging.getLogger(__name__)

TAG = ["Affiliate"]


def get_profile_or_404(user):
    return get_object_or_404(AffiliateProfile, user=user)


class ApplyAffiliateView(APIView):
    permission_classes = [IsAuthenticated]

    @extend_schema(
        summary="Apply to become an affiliate",
        description=(
            "Submit an affiliate application. affiliate_name must contain only "
            "letters and numbers and be unique. agreement must be true."
        ),
        request=AffiliateApplySerializer,
        responses={201: AffiliateStatusSerializer, 400: OpenApiTypes.OBJECT},
        tags=TAG,
    )
    def post(self, request):
        serializer = AffiliateApplySerializer(
            data=request.data, context={"request": request}
        )
        if not serializer.is_valid():
            return Response(serializer.errors, status=status.HTTP_400_BAD_REQUEST)

        data = serializer.validated_data
        affiliate, created = AffiliateProfile.objects.update_or_create(
            user=request.user,
            defaults={
                "affiliate_name": data["affiliate_name"],
                "facebook": data.get("facebook") or None,
                "instagram": data.get("instagram") or None,
                "twitter": data.get("twitter") or None,
                "tiktok": data.get("tiktok") or None,
                "agreement_accepted": data["agreement"],
            },
        )
        if created or affiliate.status == "rejected":
            affiliate.status = "pending"
            affiliate.save(update_fields=["status"])

        return Response(
            AffiliateStatusSerializer(affiliate).data,
            status=status.HTTP_201_CREATED,
        )


