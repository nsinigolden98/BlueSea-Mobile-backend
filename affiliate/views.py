class AffiliatePayoutView(APIView):
    permission_classes = [IsAuthenticated]

    @extend_schema(
        summary="Request affiliate payout",
        description=(
            "Credit all payable commissions to the authenticated affiliate's wallet. "
            "Runs the payable sweep first."
        ),
        request=None,
        responses={
            200: OpenApiTypes.OBJECT,
            400: OpenApiTypes.OBJECT,
            403: OpenApiTypes.OBJECT,
            404: OpenApiTypes.OBJECT,
        },
        tags=TAG,
    )
    def post(self, request):
        profile = get_profile_or_404(request.user)
        if not profile.is_approved:
            return Response(
                {"error": "Your affiliate application has not been approved yet."},
                status=status.HTTP_403_FORBIDDEN,
            )

        paid, total, reference = pay_out(profile)
        if total <= 0:
            return Response(
                {
                    "message": "No payable commissions to pay out.",
                    "amount_paid": "0.00",
                },
                status=status.HTTP_200_OK,
            )
        return Response(
            {
                "success": True,
                "message": f"{len(paid)} commission(s) paid out.",
                "amount_paid": str(total),
                "wallet_balance": str(profile.user.wallet.balance),
                "reference": reference,
            },
            status=status.HTTP_200_OK,
        )
